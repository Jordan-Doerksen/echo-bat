#!/usr/bin/env node
// Writes config/game.js from config/game.json, so the game can load its config with a script tag
// from file:// (the Cabinet rule: no fetch, no modules) while the JSON stays the one source every
// tool reads. `--check` exits 1 when game.js is stale, 2 when it could not look. Zero dependencies.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'config', 'game.json');
const out = join(root, 'config', 'game.js');
if (!existsSync(src)) { console.error('COULD-NOT-LOOK: config/game.json is missing'); process.exit(2); }

let cfg;
try { cfg = JSON.parse(readFileSync(src, 'utf8')); } catch (e) { console.error(`RED: config/game.json is not valid JSON: ${e.message}`); process.exit(1); }
const text = '// GENERATED by tools/build-config.mjs from config/game.json. Do not edit; edit the JSON and run npm run build.\n'
  + 'window.GAME_CONFIG = ' + JSON.stringify(cfg, null, 2).replace(/</g, '\\u003c') + ';\n';

if (process.argv.includes('--check')) {
  if (!existsSync(out)) { console.error('RED: config/game.js is missing; run npm run build'); process.exit(1); }
  const have = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  if (have !== text) { console.error('RED: config/game.js is stale against config/game.json; run npm run build'); process.exit(1); }
  console.log('GREEN: config/game.js matches config/game.json');
  process.exit(0);
}
writeFileSync(out, text);
console.log(JSON.stringify({ level: 'INFO', event: 'config_built', file: 'config/game.js', bytes: text.length }));
